const LANGUAGE_KEY = 'deck-canvas.ui-language.v1';
let language = 'ko';
try { language = globalThis.localStorage?.getItem(LANGUAGE_KEY) === 'en' ? 'en' : 'ko'; } catch { /* Private browsing defaults to Korean. */ }
export const getLanguage = () => language;
export const locale = () => language === 'en' ? 'en-US' : 'ko-KR';
export function setLanguage(value) {
  language = value === 'en' ? 'en' : 'ko';
  try { globalThis.localStorage?.setItem(LANGUAGE_KEY, language); } catch { /* UI can still switch without storage. */ }
}
export function t(key, values = {}) {
  const template = language === 'en' ? (EN[key] ?? key) : key;
  const message = String(template).replace(/\{(\w+)\}/g, (match, name) => values[name] ?? match);
  return language === 'en' ? message.replace(/\b1 cards\b/g, '1 card').replace(/\b1 copies\b/g, '1 copy') : message;
}
export function translateDocument(root = document) {
  document.documentElement.lang = language;
  for (const node of root.querySelectorAll('[data-i18n]')) node.textContent = t(node.dataset.i18n);
  for (const attribute of ['title', 'aria-label', 'placeholder']) {
    for (const node of root.querySelectorAll(`[data-i18n-${attribute}]`)) node.setAttribute(attribute, t(node.getAttribute(`data-i18n-${attribute}`)));
  }
}
